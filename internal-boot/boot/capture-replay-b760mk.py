"""Turn one read-only B760M-K probe capture into a C header for test_aggregate_graph_b760mk.c.

Emits every active (non-GET/TEST/HANDLE) open edge of the captured handle database, the
RTX child display path, the RTX PCI configuration and the four console driver bindings,
with real handles renamed to stable role ids. Nothing is inferred: a capture whose roles
cannot be found exactly once is refused, so the replay always runs on what was recorded.
"""
import importlib.util
from pathlib import Path
import re
import sys
import uuid

REPO = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
_spec = importlib.util.spec_from_file_location('make_profile', REPO / 'research' / 'profile' / 'make-profile.py')
mp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mp)

PCI_IO, PATH, GOP, TEXT = mp.PCI_IO, mp.PATH, mp.GOP, mp.TEXT_OUT
COMBO_FILE = '55987e62-1df6-41d1-9062-334fcac3e54d'
ROLES = ('H_PCI', 'H_PRIMARY', 'H_AGG', 'H_CONSOLE', 'H_NV', 'H_EDID', 'H_COMBO', 'H_GFX', 'H_TEXT')
# Console drivers in the order the test pins them: (role, file key, image GUID).
DRIVERS = (('H_EDID', ('guid', mp.MOUSE_FILE)), ('H_COMBO', ('guid', COMBO_FILE)),
           ('H_GFX', ('guid', mp.GFX_FILE)), ('H_TEXT', ('guid', mp.OUT_FILE)))


def one(values, what):
    values = list(dict.fromkeys(values))
    if len(values) != 1:
        mp.fail(f'expected exactly one {what}, found {len(values)}')
    return values[0]


def guid_c(text):
    u = uuid.UUID(text)
    tail = ','.join(f'0x{b:02x}' for b in u.bytes[8:])
    return f'{{0x{u.time_low:08x},0x{u.time_mid:04x},0x{u.time_hi_version:04x},{{{tail}}}}}'


def generate(capture):
    text = (capture / 'DIAG00.TXT').read_bytes().decode('utf-8-sig').replace('\r\n', '\n')
    blocks = mp.parse_handles(text)
    bindings = mp.parse_bindings(text.split('\n'))
    active = [(h, p, a, c, at, n) for h, b in blocks.items() for p, a, c, at, n in b['edges'] if at not in (1, 2, 4)]

    pci = one([h for h, b in blocks.items() if (mp.pci_config(b['raw']) or [0])[0] == 0x250410de], 'RTX PCI handle')
    nv = one([a for h, p, a, c, at, n in active if h == pci and p == PCI_IO and at == mp.BY_DRIVER], 'nvgop PciIo owner')
    primary = one([c for h, p, a, c, at, n in active if h == pci and p == PATH and at == mp.BY_CHILD_CONTROLLER], 'RTX display child')
    agg = one([c for h, p, a, c, at, n in active if h == primary and p == GOP and at == mp.BY_CHILD_CONTROLLER], 'aggregate GOP')
    console = one([c for h, p, a, c, at, n in active if h == agg and p == TEXT and at == mp.BY_CHILD_CONTROLLER], 'console handle')
    recorded = re.search(r'^console out=0x([0-9a-f]+) error=0x([0-9a-f]+) input=0x([0-9a-f]+)$', text, re.M)
    if not recorded or {int(v, 16) for v in recorded.groups()} != {console}:
        mp.fail('ConOut/StdErr/ConIn are not the aggregate console handle')

    # Each console driver is the agent of the edge it owns, then must be the expected image.
    owners = {'H_EDID': one([a for h, p, a, c, at, n in active if h == primary and p == mp.EDID_DISCOVERED and at == mp.BY_DRIVER], 'EDID owner'),
              'H_COMBO': one([a for h, p, a, c, at, n in active if h == primary and p == GOP and at == mp.BY_DRIVER], 'combo owner'),
              'H_GFX': one([a for h, p, a, c, at, n in active if h == agg and p == GOP and at == mp.BY_DRIVER], 'console_gfx owner'),
              'H_TEXT': one([a for h, p, a, c, at, n in active if h == agg and p == TEXT and at == mp.BY_DRIVER], 'console_text owner')}
    ids = {pci: 'H_PCI', primary: 'H_PRIMARY', agg: 'H_AGG', console: 'H_CONSOLE', nv: 'H_NV'}
    drivers = []
    for role, key in DRIVERS:
        rec = one([b['handle'] for b in bindings if b['handle'] == owners[role]], f'{role} binding record')
        rec = next(b for b in bindings if b['handle'] == rec)
        if rec['file'] != key:
            mp.fail(f'{role} owner is {rec["file"]}, not {key}')
        ids[rec['handle']] = role
        drivers.append((role, rec, key[1]))
    images = {}
    for role, rec, _ in drivers:
        if rec['image'] != rec['handle']:
            images[rec['image']] = f'(H_IMAGE+{len(images)})'
    others = {}

    def name(h):
        if not h:
            return '0'
        if h in ids:
            return ids[h]
        if h in images:
            return images[h]
        others.setdefault(h, f'(H_OTHER+{len(others)})')
        return others[h]

    path = mp.path_of(blocks[primary]['raw'])
    config = mp.pci_config(blocks[pci]['raw'])
    if not path or len(path) != 36 or not config:
        mp.fail('RTX child path or PCI configuration missing')
    lines = [f'/* Generated by capture-replay-b760mk.py from {capture.name}. Do not edit. */',
             '#pragma once',
             'enum { ' + ','.join(f'{r}={i + 1}' for i, r in enumerate(ROLES)) + ',H_IMAGE=0x100,H_OTHER=0x1000 };',
             f'#define CAP_SCAN "{capture.name}"',
             f'#define CAP_EDGE_COUNT {len(active)}U',
             'static const CAP_EDGE CapEdges[]={']
    for h, p, a, c, at, n in active:
        lines.append(f' {{{name(h)},{name(a)},{name(c)},{guid_c(p)},0x{at:x},{n}}},')
    lines += ['};',
              'static const UINT8 CapChildPath[36]={' + ','.join(str(b) for b in path) + '};',
              'static const UINT32 CapRtxConfig[16]={' + ','.join(f'0x{v:08x}' for v in config) + '};',
              'static const CAP_DRIVER CapDrivers[4]={']
    for role, rec, file in drivers:
        image = name(rec['image'])
        lines.append(f' {{{role},{image},{guid_c(file)},0x{rec["base"]:x},0x{rec["size"]:x},'
                     f'0x{rec["stop"] - rec["base"]:x},0x{rec["version"]:x},{rec["code-type"]}}},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('usage: capture-replay-b760mk.py <capture-dir> <out.h>')
    try:
        Path(sys.argv[2]).write_text(generate(Path(sys.argv[1])), encoding='ascii')
    except mp.Refused as error:
        sys.exit(f'capture refused: {error}')
